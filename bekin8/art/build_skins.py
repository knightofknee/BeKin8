# art/build_skins.py
# Turns the painted source images in art/in/ into app assets for the painted skins other than
# The Beacons (that one has its own script, build_beacons.py):
#
#   Old Guard        castle-bg.png                 + castle-basket.png
#   Campfire         campfire-bg.png               + campfire-logs.png
#   Smoke Signal     smoke-bg.png                  + smoke-fire.png
#
#   python3 art/build_skins.py            build everything
#   python3 art/build_skins.py --mock     also write phone-sized mock-ups to art/mock-<skin>.png
#
# Writes assets/images/skins/<skin>/*.webp and GENERATES components/scenes/paintedArt.ts.
# Placement lives in the SKINS table below: where the beacon stands on each painting (ledge), how
# wide the painting is drawn (zoom, in screen widths), and how the sprite sits in the 180px
# structure box (top/foot, on the 0..100 scale the structures use).
import json
import os
import sys

from PIL import Image

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from build_beacons import ROOT, SRC, firelit, load_cut, mul, trim  # noqa: E402

OUT_ROOT = os.path.join(ROOT, "assets", "images", "skins")
TS = os.path.join(ROOT, "components", "scenes", "paintedArt.ts")

SKINS = {
    "castleWall": {
        "dir": "castle", "bg": "castle-bg.png", "bg_out": "wall-bg.webp",
        "sprite": "castle-basket.png", "sprite_out": "basket", "erode": 3,
        "ledge": (0.5, 0.700), "zoom": 1.0,
        "box": (13, 95),                      # sprite top / foot in the structure box
        "night": (0.56, 0.62, 0.78), "fire_at": (0.5, 0.20), "fire_strength": 1.3,
        # the distant watchtower that answers (top of the tower on the painting)
        "extra": {"answer": (0.847, 0.398)},
    },
    "campfire": {
        "dir": "campfire", "bg": "campfire-bg.png", "bg_out": "bg.webp",
        "sprite": "campfire-logs.png", "sprite_out": "logs", "erode": 0,
        "ledge": (0.5, 0.815), "zoom": 1.12,
        "box": (34, 95),
        "night": (0.62, 0.70, 0.86), "fire_at": (0.5, 0.55), "fire_strength": 1.5,
        "extra": {},
    },
    "smoke": {
        "dir": "smoke", "bg": "smoke-bg.png", "bg_out": "bg.webp",
        "sprite": "smoke-fire.png", "sprite_out": "fire", "erode": 0,
        "ledge": (0.5, 0.880), "zoom": 1.2,
        "box": (62, 95),
        "night": (1.0, 1.0, 1.0), "fire_at": (0.5, 0.55), "fire_strength": 1.15,
        "extra": {},
    },
}


def save(im, d, name, q=86):
    os.makedirs(os.path.join(OUT_ROOT, d), exist_ok=True)
    im.save(os.path.join(OUT_ROOT, d, name), "WEBP", quality=q, method=6)


def build_bg(cfg):
    """Fade the top edge to flat sky and the bottom edge to a flat floor colour, so the app can
    carry both on past the painting."""
    bg = Image.open(os.path.join(SRC, cfg["bg"])).convert("RGB")
    w, h = bg.size
    top = bg.crop((0, 0, w, 16)).resize((1, 1), Image.BOX).getpixel((0, 0))
    bot = bg.crop((0, h - 40, w, h)).resize((1, 1), Image.BOX).getpixel((0, 0))
    floor = tuple(int(c * 0.55) for c in bot)
    col = Image.new("L", (1, h), 0)
    cp = col.load()
    for y in range(h):
        cp[0, y] = int(255 * max(0.0, 1 - (y / h) / 0.05))
    bg = Image.composite(Image.new("RGB", bg.size, top), bg, col.resize(bg.size))
    for y in range(h):
        cp[0, y] = int(255 * max(0.0, ((y / h) - 0.90) / 0.10) ** 1.3)
    bg = Image.composite(Image.new("RGB", bg.size, floor), bg, col.resize(bg.size))
    save(bg, cfg["dir"], cfg["bg_out"], 84)
    return bg, top, floor


def build_sprite(cfg):
    cut = load_cut(cfg["sprite"], cfg["erode"])
    (cut,) = trim(cut)
    dark = mul(cut, cfg["night"])
    fx, fy = cfg["fire_at"]
    lit = firelit(cut, dark, cut.width * fx, cut.height * fy, cut.width * 0.85, cfg["fire_strength"])
    size = (480, int(cut.height * 480 / cut.width))
    save(dark.resize(size, Image.LANCZOS), cfg["dir"], cfg["sprite_out"] + ".webp", 90)
    save(lit.resize(size, Image.LANCZOS), cfg["dir"], cfg["sprite_out"] + "-lit.webp", 90)
    return cut.width / cut.height


def hexc(c):
    return "#%02X%02X%02X" % tuple(c)


def build():
    lines = [
        "// components/scenes/paintedArt.ts",
        "// GENERATED by art/build_skins.py from the paintings in art/in/. Do not edit by hand:",
        "// change the SKINS table in that script and run it again.",
        "export type PaintedArt = {",
        "  bg: number;",
        "  /** painting width / height */",
        "  aspect: number;",
        "  /** flat colours the painting's top and bottom edges fade to */",
        "  sky: string; floor: string;",
        "  /** where the beacon stands on the painting (fractions of the image) */",
        "  ledge: { u: number; v: number };",
        "  /** the painting is drawn this many screen-widths wide */",
        "  zoom: number;",
        "  /** the beacon sprite, dark and firelit, and where it sits in the 0..100 structure box */",
        "  sprite: number; spriteLit: number; spriteAspect: number;",
        "  top: number; foot: number;",
        "  /** other marked points on the painting (fractions of the image) */",
        "  extra: Record<string, { u: number; v: number }>;",
        "};",
        "",
    ]
    out = {}
    for key, cfg in SKINS.items():
        bg, top, floor = build_bg(cfg)
        aspect = build_sprite(cfg)
        d = cfg["dir"]
        extra = {k: {"u": v[0], "v": v[1]} for k, v in cfg["extra"].items()}
        lines += [
            f"export const {key}Art: PaintedArt = {{",
            f"  bg: require('../../assets/images/skins/{d}/{cfg['bg_out']}'),",
            f"  aspect: {round(bg.width / bg.height, 4)},",
            f"  sky: '{hexc(top)}', floor: '{hexc(floor)}',",
            f"  ledge: {{ u: {cfg['ledge'][0]}, v: {cfg['ledge'][1]} }},",
            f"  zoom: {cfg['zoom']},",
            f"  sprite: require('../../assets/images/skins/{d}/{cfg['sprite_out']}.webp'),",
            f"  spriteLit: require('../../assets/images/skins/{d}/{cfg['sprite_out']}-lit.webp'),",
            f"  spriteAspect: {round(aspect, 4)},",
            f"  top: {cfg['box'][0]}, foot: {cfg['box'][1]},",
            f"  extra: {json.dumps(extra)},",
            "};",
            "",
        ]
        out[key] = (cfg, aspect, top, floor)
    with open(TS, "w") as f:
        f.write("\n".join(lines))
    return out


def mock(key, cfg, aspect, floor, top, lit):
    """Phone-sized preview with the same layout maths as PaintedBackdrop / PaintedSprite."""
    W, H = 402, 874
    box_top = 470                      # where home puts the 180px structure box on this phone
    foot_y = box_top + 180 * cfg["box"][1] / 100
    img_w = W * cfg["zoom"]
    img_h = img_w * 1.5
    ix = (W - img_w) / 2
    iy = foot_y - cfg["ledge"][1] * img_h
    can = Image.new("RGBA", (W, H), tuple(floor) + (255,))
    if iy > 0:
        can.paste(Image.new("RGBA", (W, int(iy) + 2), tuple(top) + (255,)), (0, 0))
    b = Image.open(os.path.join(OUT_ROOT, cfg["dir"], cfg["bg_out"])).convert("RGBA")
    b = b.resize((int(img_w), int(img_h)), Image.LANCZOS)
    can.paste(b, (int(ix), int(iy)))
    name = cfg["sprite_out"] + ("-lit" if lit else "") + ".webp"
    sp = Image.open(os.path.join(OUT_ROOT, cfg["dir"], name)).convert("RGBA")
    sh = 180 * (cfg["box"][1] - cfg["box"][0]) / 100
    sw = sh * aspect
    sp = sp.resize((int(sw), int(sh)), Image.LANCZOS)
    can.alpha_composite(sp, (int(W / 2 - sw / 2), int(foot_y - sh)))
    can.convert("RGB").save(os.path.join(ROOT, "art", f"mock-{key}{'-lit' if lit else ''}.png"))


if __name__ == "__main__":
    built = build()
    if "--mock" in sys.argv:
        for key, (cfg, aspect, top, floor) in built.items():
            mock(key, cfg, aspect, floor, top, False)
    print("ok", ", ".join(built))
